"""Evaluate simple next-card baselines on held-out matches.

Expected input is data/sequences/sequences.json, generated by
prepare_sequences.py. Each top-level sequence is treated as one match, so
contexts from the same match never leak across train/test.
"""
from __future__ import annotations

import argparse
import json
import math
import random
from pathlib import Path

from baselines import FrequencyBaseline, TransitionBaseline

try:
    from config import PROJECT_ROOT
except ImportError:  # Supports running from unusual working directories.
    PROJECT_ROOT = Path(__file__).resolve().parent.parent

DEFAULT_SEQUENCES = PROJECT_ROOT / "data" / "sequences" / "sequences.json"


def split_matches(
    sequences: list[list[str]], test_fraction: float = 0.2, seed: int = 42
) -> tuple[list[list[str]], list[list[str]]]:
    if not 0 < test_fraction < 1:
        raise ValueError("test_fraction must be between 0 and 1")
    if len(sequences) < 2:
        raise ValueError("At least two match sequences are required")
    indices = list(range(len(sequences)))
    random.Random(seed).shuffle(indices)
    test_count = max(1, min(len(sequences) - 1, round(len(indices) * test_fraction)))
    test_indices = set(indices[:test_count])
    train = [seq for i, seq in enumerate(sequences) if i not in test_indices]
    test = [seq for i, seq in enumerate(sequences) if i in test_indices]
    return train, test


def evaluate(model, sequences: list[list[str]], top_k: int = 3) -> dict[str, float | int]:
    samples = 0
    top1 = 0
    topk = 0
    loss_sum = 0.0
    for sequence in sequences:
        for index in range(1, len(sequence)):
            history = sequence[:index]
            target = sequence[index]
            probabilities = model.predict_proba(history)
            if target not in probabilities:
                # A card absent from training is genuinely out of vocabulary.
                samples += 1
                continue
            ranked = sorted(probabilities, key=lambda card: (-probabilities[card], card))
            top1 += bool(ranked and ranked[0] == target)
            topk += target in ranked[:top_k]
            loss_sum -= math.log(max(probabilities[target], 1e-12))
            samples += 1

    if not samples:
        return {"samples": 0, "top1_accuracy": 0.0, "top3_accuracy": 0.0, "cross_entropy": 0.0}
    return {
        "samples": samples,
        "top1_accuracy": top1 / samples,
        "top3_accuracy": topk / samples,
        "cross_entropy": loss_sum / samples,
    }


def main() -> None:
    parser = argparse.ArgumentParser(description="Evaluate next-card baselines by held-out match")
    parser.add_argument("--sequences", type=Path, default=DEFAULT_SEQUENCES)
    parser.add_argument("--test-fraction", type=float, default=0.2)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--top-k", type=int, default=3)
    args = parser.parse_args()

    if not args.sequences.exists():
        raise FileNotFoundError(
            f"{args.sequences} not found. Run python src/prepare_sequences.py first."
        )
    sequences = json.loads(args.sequences.read_text(encoding="utf-8"))
    sequences = [
        [str(card) for card in sequence if card]
        for sequence in sequences
        if isinstance(sequence, list) and len(sequence) >= 2
    ]
    train, test = split_matches(sequences, args.test_fraction, args.seed)

    models = {
        "frequency": FrequencyBaseline().fit(train),
        "last-card-transition": TransitionBaseline().fit(train),
    }
    print(f"Matches: train={len(train)}, test={len(test)}, seed={args.seed}")
    print(f"Evaluation target: next observed card; Top-K={args.top_k}")
    for name, model in models.items():
        metrics = evaluate(model, test, args.top_k)
        print(
            f"{name:24s} samples={metrics['samples']:5d} "
            f"top1={metrics['top1_accuracy']:.3f} "
            f"top{args.top_k}={metrics['top3_accuracy']:.3f} "
            f"cross_entropy={metrics['cross_entropy']:.3f}"
        )


if __name__ == "__main__":
    main()
